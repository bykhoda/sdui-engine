#!/usr/bin/env node
// Generates the human reference for the contract straight from the JSON schema, so the
// docs can never drift from what the renderers actually enforce. Emits Markdown under
// docs/reference/. Run after any schema change (a CI drift-gate can diff the output).
//
// Usage: node spec/tools/gen-reference.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SCHEMA = JSON.parse(readFileSync(join(ROOT, 'spec/schema/sdui.schema.json'), 'utf8'));
const D = SCHEMA.$defs;
const deref = (n) => (n && n.$ref ? D[n.$ref.split('/').pop()] : n);
const OUT = join(ROOT, 'docs/reference');
mkdirSync(OUT, { recursive: true });

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
function typeStr(s) {
  if (!s) return '—';
  if (s.$ref) return `\`${s.$ref.split('/').pop()}\``;
  if (s.enum) return s.enum.map((e) => `\`${e}\``).join(' · ');
  if (s.oneOf || s.anyOf) return (s.oneOf || s.anyOf).map(typeStr).join(' \\| ');
  if (s.const !== undefined) return `\`${s.const}\``;
  if (s.type === 'array') return `${typeStr(s.items)}[]`;
  if (s.type === 'object') return 'object';
  return `\`${s.type || 'any'}\``;
}
function propRows(spec) {
  const props = spec?.properties || {};
  const req = new Set(spec?.required || []);
  const keys = Object.keys(props).filter((k) => k !== 'type');
  if (!keys.length) return '_No properties beyond the shared ones (`modifiers`, `children`)._\n';
  let md = '| Prop | Type | Req | Description |\n|---|---|:--:|---|\n';
  for (const k of keys) {
    const p = props[k];
    md += `| \`${k}\` | ${typeStr(p)} | ${req.has(k) ? '✓' : ''} | ${esc(p.description)} |\n`;
  }
  return md;
}

const header = (title, sub) =>
  `<!-- GENERATED by spec/tools/gen-reference.mjs — do not edit by hand. -->\n# ${title}\n\n> ${sub}\n\n`;

// ---- Components ----
let comp = header('Component reference', 'Every component in the contract, generated from the schema. iOS is the reference renderer; see PARITY.md for per-platform support.');
const branches = (D.Component.allOf || []).map((b) => ({ type: b.if?.properties?.type?.const, spec: deref(b.then) })).filter((b) => b.type).sort((a, b) => a.type.localeCompare(b.type));
comp += `**${branches.length} components:** ` + branches.map((b) => `[\`${b.type}\`](#${b.type})`).join(' · ') + '\n\n';
for (const b of branches) {
  comp += `## ${b.type}\n\n`;
  if (b.spec?.description) comp += `${b.spec.description}\n\n`;
  comp += propRows(b.spec) + '\n';
}
writeFileSync(join(OUT, 'components.md'), comp);

// ---- Modifiers ----
let mod = header('Modifier reference', 'Platform-neutral visual + interaction modifiers applied to any component (`node.modifiers`). A closed set — an unknown key fails validation.');
mod += propRows(D.Modifiers);
writeFileSync(join(OUT, 'modifiers.md'), mod);

// ---- Actions ----
let act = header('Action reference', 'The closed action vocabulary interpreted identically by every renderer. Fields below are per-kind; `analytics` may accompany any action.');
const kinds = (D.Action.properties.action.enum || []).slice().sort();
const thenByKind = {};
for (const br of D.Action.allOf || []) { const k = br.if?.properties?.action?.const; if (k) thenByKind[k] = br.then; }
act += `**${kinds.length} actions:** ` + kinds.map((k) => `[\`${k}\`](#${k})`).join(' · ') + '\n\n';
for (const k of kinds) {
  act += `## ${k}\n\n`;
  const then = thenByKind[k];
  act += then?.properties ? propRows(then) + '\n' : '_No fields beyond `action` (and optional `analytics`)._\n\n';
}
writeFileSync(join(OUT, 'actions.md'), act);

// ---- Index ----
const nMod = Object.keys(D.Modifiers.properties).length;
writeFileSync(join(OUT, 'README.md'),
  header('Contract reference', 'Generated from `spec/schema/sdui.schema.json`. The single source of truth for what a screen may contain; kept in sync by a CI drift gate.') +
  `| Reference | Count |\n|---|:--:|\n` +
  `| [Components](components.md) | ${branches.length} |\n` +
  `| [Modifiers](modifiers.md) | ${nMod} |\n` +
  `| [Actions](actions.md) | ${kinds.length} |\n\n` +
  `Per-platform support for each is tracked in [PARITY.md](../../PARITY.md). ` +
  `Regenerate with \`node spec/tools/gen-reference.mjs\`.\n`);

console.log(`✓ wrote docs/reference/{README,components,modifiers,actions}.md — ${branches.length} components, ${nMod} modifiers, ${kinds.length} actions`);
